#!/usr/bin/env node
/**
 * Builds the acceptance-testing books as Word documents, into docs/testing by default.
 * Every expected figure in here was produced by scripts/uat-scenario.mjs running the real software
 * — see docs/testing/verified-run.txt. Edit this file, never the .docx: a hand edit to a document
 * is lost the next time they are rebuilt.
 *
 *   node scripts/make-testing-docs.mjs [output directory]
 */
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
import { execSync } from "node:child_process";

// `docx` is not a dependency of the product — it is only needed to build these documents.
// Use it from wherever it happens to be installed (`npm i -g docx` if it is nowhere).
const req = createRequire(import.meta.url);
let docx;
try { docx = req("docx"); }
catch { docx = req(path.join(execSync("npm root -g").toString().trim(), "docx")); }
const {
  AlignmentType, BorderStyle, Document, Footer, HeadingLevel, PageBreak, Packer, Paragraph,
  ShadingType, Table, TableCell, TableRow, TextRun, VerticalAlign, WidthType,
} = docx;

const OUT = process.argv[2] || path.join(path.dirname(new URL(import.meta.url).pathname), "..", "docs", "testing");
fs.mkdirSync(OUT, { recursive: true });

const W = 9000;                      // usable width, DXA
const INK = "1F2937", BLUE = "0C4A6E", MUTED = "64748B", RULE = "CBD5E1";
const HEAD_BG = "E0F2FE", NOTE_BG = "F1F5F9", WARN_BG = "FEF3C7", BOX_BG = "FFFFFF";

/** tiny markup: **bold** and *italic* */
const runs = (text, opts = {}) =>
  String(text).split(/(\*\*[^*]+\*\*|\*[^*]+\*)/g).filter(Boolean).map((piece) => {
    const bold = piece.startsWith("**");
    const ital = !bold && piece.startsWith("*") && piece.endsWith("*");
    return new TextRun({
      text: bold ? piece.slice(2, -2) : ital ? piece.slice(1, -1) : piece,
      bold: bold || opts.bold, italics: ital || opts.italics,
      size: opts.size ?? 20, color: opts.color ?? INK, font: "Calibri" });
  });

const P = (text, opts = {}) => new Paragraph({
  children: runs(text ?? "", opts),
  spacing: { before: opts.before ?? 60, after: opts.after ?? 100, line: 276 },
  alignment: opts.align, indent: opts.indent,
});

const cell = (text, o = {}) => new TableCell({
  width: { size: o.w, type: WidthType.DXA },
  shading: o.bg ? { type: ShadingType.CLEAR, fill: o.bg, color: "auto" } : undefined,
  margins: { top: 90, bottom: 90, left: 120, right: 120 },
  verticalAlign: VerticalAlign.TOP,
  children: (Array.isArray(text) ? text : [text]).map((t) =>
    new Paragraph({ children: runs(t ?? "", { bold: o.bold, size: o.size ?? 19, color: o.color }),
                    alignment: o.align, spacing: { before: 0, after: 0, line: 252 } })),
});

const borders = {
  top: { style: BorderStyle.SINGLE, size: 2, color: RULE },
  bottom: { style: BorderStyle.SINGLE, size: 2, color: RULE },
  left: { style: BorderStyle.SINGLE, size: 2, color: RULE },
  right: { style: BorderStyle.SINGLE, size: 2, color: RULE },
  insideHorizontal: { style: BorderStyle.SINGLE, size: 2, color: RULE },
  insideVertical: { style: BorderStyle.SINGLE, size: 2, color: RULE },
};

const table = (widths, headRow, bodyRows, opts = {}) => new Table({
  columnWidths: widths, width: { size: widths.reduce((a, b) => a + b, 0), type: WidthType.DXA }, borders,
  rows: [
    ...(headRow ? [new TableRow({ tableHeader: true, children: headRow.map((h, i) =>
      cell(h, { w: widths[i], bg: HEAD_BG, bold: true, color: BLUE, align: opts.headAlign?.[i] })) })] : []),
    ...bodyRows.map((r) => new TableRow({ children: r.map((c, i) =>
      cell(c, { w: widths[i], align: opts.align?.[i], bg: opts.bg?.(r, i) })) })),
  ],
});

const h1 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_1, spacing: { before: 380, after: 140 },
  children: [new TextRun({ text: t, bold: true, size: 30, color: BLUE, font: "Calibri" })],
  border: { bottom: { style: BorderStyle.SINGLE, size: 6, color: HEAD_BG, space: 6 } } });
const h2 = (t) => new Paragraph({ heading: HeadingLevel.HEADING_2, spacing: { before: 280, after: 100 },
  children: [new TextRun({ text: t, bold: true, size: 23, color: BLUE, font: "Calibri" })] });

const callout = (text, bg = NOTE_BG) => new Table({
  columnWidths: [W], width: { size: W, type: WidthType.DXA },
  borders: { top: { style: BorderStyle.SINGLE, size: 2, color: bg }, bottom: { style: BorderStyle.SINGLE, size: 2, color: bg },
             left: { style: BorderStyle.SINGLE, size: 18, color: bg === WARN_BG ? "D97706" : "0EA5E9" },
             right: { style: BorderStyle.SINGLE, size: 2, color: bg },
             insideHorizontal: { style: BorderStyle.NONE }, insideVertical: { style: BorderStyle.NONE } },
  rows: [new TableRow({ children: [cell(Array.isArray(text) ? text : [text], { w: W, bg, size: 19 })] })],
});

/** the step table every book is built from */
const steps = (rows) => table([520, 3380, 3600, 1500],
  ["#", "What to do", "What must happen", "✔ / ✘ and voucher no."],
  rows.map((r, i) => [String(i + 1), r[0], r[1], ""]),
  { align: [AlignmentType.CENTER, undefined, undefined, AlignmentType.CENTER],
    headAlign: [AlignmentType.CENTER, undefined, undefined, AlignmentType.CENTER] });

/** the end-of-book checklist: empty first cell is the tick box */
const checklist = (items) => table([620, 7180, 1200],
  ["Tick", "This must be true before the book is signed off", "Initials"],
  items.map((t) => ["", t, ""]),
  { headAlign: [AlignmentType.CENTER, undefined, AlignmentType.CENTER],
    bg: (_r, i) => (i === 0 ? BOX_BG : undefined) });

const signoff = () => table([2400, 6600],
  null,
  [["Tester (name)", ""], ["Date", ""], ["Result", "Pass   /   Pass with notes   /   Fail   (circle one)"],
   ["Notes and anything the screen said that this book does not predict", ""], ["", ""], ["", ""]],
  { });

const cover = (b) => [
  new Paragraph({ spacing: { after: 40 }, children: [new TextRun({ text: b.no.toUpperCase(), bold: true, size: 19, color: MUTED, font: "Calibri", characterSpacing: 40 })] }),
  new Paragraph({ spacing: { after: 60 }, children: [new TextRun({ text: b.title, bold: true, size: 44, color: BLUE, font: "Calibri" })] }),
  new Paragraph({ spacing: { after: 240 }, border: { bottom: { style: BorderStyle.SINGLE, size: 8, color: "0EA5E9", space: 8 } },
    children: [new TextRun({ text: b.subtitle, size: 22, color: MUTED, font: "Calibri", italics: true })] }),
  table([2200, 6800], null, [
    ["What this book proves", b.proves],
    ["Who runs it", b.who],
    ["How long it takes", b.howLong],
    ["Do this first", b.before],
  ], {}),
  P(""),
];

const render = (blocks) => blocks.flatMap((bl) => {
  const [kind, arg, arg2] = bl;
  if (kind === "h1") return [h1(arg)];
  if (kind === "h2") return [h2(arg)];
  if (kind === "p") return [P(arg)];
  if (kind === "small") return [P(arg, { size: 18, color: MUTED })];
  if (kind === "note") return [callout(arg), P("")];
  if (kind === "warn") return [callout(arg, WARN_BG), P("")];
  if (kind === "steps") return [steps(arg), P("")];
  if (kind === "table") return [table(arg.widths, arg.head, arg.rows, arg.opts || {}), P("")];
  if (kind === "check") return [h2(arg2 || "Checklist"), checklist(arg), P("")];
  if (kind === "pagebreak") return [new Paragraph({ children: [new PageBreak()] })];
  throw new Error("unknown block " + kind);
});

function build(book) {
  const doc = new Document({
    creator: "Genius ITens", title: `${book.no} — ${book.title}`,
    styles: { default: { document: { run: { font: "Calibri", size: 20, color: INK } } } },
    sections: [{
      properties: { page: { margin: { top: 1100, bottom: 1000, left: 1150, right: 1150 } } },
      footers: { default: new Footer({ children: [new Paragraph({ alignment: AlignmentType.CENTER,
        children: [new TextRun({ text: `FX Desk acceptance testing · ${book.no} — ${book.title} · Genius ITens`, size: 16, color: MUTED, font: "Calibri" })] })] }) },
      children: [
        ...cover(book),
        ...render(book.body),
        h2("Sign-off"),
        signoff(),
      ],
    }],
  });
  return Packer.toBuffer(doc).then((buf) => {
    const file = path.join(OUT, `${book.file}.docx`);
    fs.writeFileSync(file, buf);
    console.log(`  ${path.basename(file)}`);
  });
}

